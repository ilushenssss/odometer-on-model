def fmt(v):
    if isinstance(v, tuple):
        return "[" + ", ".join(fmt(x) for x in v) + "]"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, float):
        return f"{v:g}"
    return str(v)


def table(obj, desc, prefix):
    lines = ["| параметр | по умолчанию | ед. | описание |", "|---|---|---|---|"]
    for f in fields(obj):
        unit, text = desc.get(f.name, ("", ""))
        lines.append(f"| `{prefix}{f.name}` | {fmt(getattr(obj, f.name))} | {unit} | {text} |")
    missing = [f.name for f in fields(obj) if f.name not in desc]
    if missing:
        raise SystemExit(f"no description for {missing}")
    return lines


def main():
    out = ["### Параметры трамвая (`tram.*` в YAML ноды)", ""] + table(TramParams(), TRAM, "tram.")
    out += ["", "### Параметры оценивателя (`nav.*` в YAML ноды)", ""] + table(NavigatorParams(), NAV, "nav.")
    out += ["", "### Только симулятор: датчики (`SensorParams`) и сцепление (`AdhesionParams`)", "",
            "Эти параметры описывают «реальный» трамвай в симуляторе и навигатору **не известны**.", ""]
    out += table(SensorParams(), SENS, "") + [""] + table(AdhesionParams(), ADH, "")
    path = os.path.join(ROOT, "docs", "PARAMETERS.md")
    with open(path) as f:
        text = f.read()
    a, b = text.index("<!-- PARAMS:BEGIN -->"), text.index("<!-- PARAMS:END -->")
    text = text[:a] + "<!-- PARAMS:BEGIN -->\n" + "\n".join(out) + "\n" + text[b:]
    with open(path, "w") as f:
        f.write(text)
    print(f"{path}: {len(fields(TramParams)) + len(fields(NavigatorParams))} navigator parameters documented")


if __name__ == "__main__":
    main()
